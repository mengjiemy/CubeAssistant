public struct CubeState: Equatable {
    public var facelets: [Int]  // 长度 54，值 0..5

    public init(solved: Bool = true) {
        if solved {
            facelets = (0..<54).map { $0 / 9 }  // 每面 9 格同色
        } else {
            facelets = Array(0..<54)
        }
    }

    public init(facelets: [Int]) {
        precondition(facelets.count == 54)
        self.facelets = facelets
    }

    /// 判断是否为已复原状态
    public var isSolved: Bool {
        for f in 0..<6 {
            let base = f * 9
            for k in 1..<9 where facelets[base + k] != facelets[base] { return false }
        }
        return true
    }

    /// 应用一次转动（moveIndex 对应 movePerms 下标）
    public mutating func apply(_ moveIndex: Int) {
        let p = movePerms[moveIndex]
        let old = facelets
        for i in 0..<54 { facelets[i] = old[p[i]] }
    }

    public func applying(_ moveIndex: Int) -> CubeState {
        var c = self; c.apply(moveIndex); return c
    }

    /// 从 6 个面的颜色矩阵构建（每个 faceColors 为 9 个颜色 id，顺序 row-major）
    public init(faces colors: [[Int]]) {
        precondition(colors.count == 6 && colors.allSatisfy { $0.count == 9 })
        facelets = colors.flatMap { $0 }
    }
}

#if DEBUG
extension CubeState {
    /// 内部自检：每个基础转动应用 4 次应回到原状态
    static func runSelfCheck() -> Bool {
        var ok = true
        for m in 0..<6 {  // U R F D L B 在 movePerms 的 0,3,6,9,12,15
            var c = CubeState(solved: true)
            for _ in 0..<4 { c.apply(m * 3) }  // 用基础转动（x1）做 4 次
            if !c.isSolved { ok = false; print("转动 \(m) 4 次未还原") }
        }
        return ok
    }
}
#endif
